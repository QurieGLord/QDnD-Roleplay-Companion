/// Campaigns for the opt-in Cycle packages: each class hero keeps a journal
/// of their own — names, notes, quests, sessions and threads — so the board,
/// the tape and the Atlas have a story to show. The paladin's is the
/// accepted wave 4 prototype's (Elian's story).
void writeJournalCampaign(Character hero, {String prefix = '', String? story}) {
  final c = _stories[story ?? _storyOf(hero.characterClass)] ?? _stories['paladin']!;
  String id(String raw) => '$prefix$raw';
  String key(String raw) => '${raw[0]}:${id(raw.substring(2))}';
  DateTime day(int session) => DateTime(2026, 10, 1 + session * 2, 20);
  hero.journalNotes = [
    for (final n in c.notes)
      JournalNote(
          id: id(n.id),
          title: n.title,
          category: n.category,
          content: n.text,
          tags: List.of(n.tags),
          isPinned: n.pinned,
          createdAt: day(n.session ?? c.sessions),
          updatedAt: day(n.session ?? c.sessions)),
  ];
  hero.quests = [
    for (final q in c.quests)
      Quest(
          id: id(q.id),
          title: q.title,
          description: q.text,
          status: q.status,
          createdAt: day(q.session),
          completedAt: q.status == QuestStatus.active ? null : day(q.session),
          objectives: [
            for (final s in q.steps)
              QuestObjective(
                  description: s.startsWith('+') ? s.substring(1) : s,
                  isCompleted: s.startsWith('+'))
          ]),
  ];
  final g = JournalGraph(sessions: c.sessions, entities: [
    for (final e in c.names)
      JournalEntity(
          id: id(e.id),
          name: e.name,
          kind: e.kind,
          aliases: List.of(e.aliases),
          description: e.about),
  ]);
  void tie(String record, int? session, List<String> records, List<String> manual) {
    final links = g.forRecord(key(record));
    links.session = session;
    links.records.addAll(records.map(key));
    links.manual.addAll(manual.map(id));
  }

  for (final n in c.notes) {
    tie(n.key, n.session, n.links, n.manual);
  }
  for (final q in c.quests) {
    tie(q.key, q.session, q.links, q.manual);
  }
  g.noteOrder.addAll([
    for (final n in c.notes)
      if (n.pinned) 'n:${id(n.id)}',
    for (final n in c.notes)
      if (!n.pinned) 'n:${id(n.id)}',
  ]);
  g.questOrder.addAll(c.quests.map((q) => 'q:${id(q.id)}'));
  JournalService.reconcile(hero, g);
  hero.journalData = g.toJson();
}

String _storyOf(String classId) {
  final id = classId.toLowerCase();
  for (final name in _stories.keys) {
    if (id.contains(name)) return name;
  }
  return 'paladin';
}

class _Story {
  const _Story(this.sessions, this.names, this.notes, this.quests);
  final int sessions;
  final List<_Name> names;
  final List<_Note> notes;
  final List<_Quest> quests;
}

class _Name {
  const _Name(this.id, this.name, this.kind, this.about, [this.aliases = const []]);
  final String id, name, about;
  final JournalEntityKind kind;
  final List<String> aliases;
}

class _Note {
  const _Note(this.id, this.title, this.category, this.session, this.text,
      {this.tags = const [],
      this.pinned = false,
      this.links = const [],
      this.manual = const []});
  final String id, title, text;
  final NoteCategory category;
  final int? session;
  final List<String> tags, links, manual;
  final bool pinned;
  String get key => 'n:$id';
}

class _Quest {
  const _Quest(this.id, this.title, this.status, this.session, this.text, this.steps,
      {this.links = const [], this.manual = const []});
  final String id, title, text;
  final QuestStatus status;
  final int session;

  /// Steps; a leading «+» marks one already done.
  final List<String> steps, links, manual;
  String get key => 'q:$id';
}

